// Builds src/lib/map/world-path.ts from Natural Earth's 1:110m land polygons
// (public domain, https://www.naturalearthdata.com). Run once; the output is
// committed, so the site needs no map library or tile service.
//
//   curl -L -o ne_110m_land.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
//   node scripts/build-world-path.mjs ne_110m_land.geojson

import { readFileSync, writeFileSync } from "node:fs";
import { MAP } from "../src/lib/map/projection.mjs";

const [, , input] = process.argv;
if (!input) throw new Error("Usage: node scripts/build-world-path.mjs <ne_110m_land.geojson>");

const { features } = JSON.parse(readFileSync(input, "utf8"));
const x = (lon) => ((lon + 180) / 360) * MAP.width;
const y = (lat) => ((MAP.north - lat) / (MAP.north - MAP.south)) * MAP.height;
const r = (n) => Math.round(n * 10) / 10;

const rings = features.flatMap((f) =>
  f.geometry.type === "Polygon" ? f.geometry.coordinates : f.geometry.coordinates.flat()
);
const d = rings
  .map((ring) => "M" + ring.map(([lon, lat]) => `${r(x(lon))} ${r(y(lat))}`).join("L") + "Z")
  .join("");

writeFileSync(
  "src/lib/map/world-path.ts",
  `// Generated by scripts/build-world-path.mjs from Natural Earth 1:110m land\n// (public domain). Do not edit by hand.\nexport const worldPath =\n  ${JSON.stringify(d)};\n`
);
console.log(`${rings.length} rings, ${d.length} characters`);
